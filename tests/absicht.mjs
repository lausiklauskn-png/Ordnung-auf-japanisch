// „Was möchtest du heute tun?“ ohne Browser: Beispielsätze → Raum, Mittel, Fleck, Gewohnheit, Monat.
import fs from 'node:fs';
import { bauen } from '../tools/inhalt-bauen.mjs';
await import('../assets/absicht.js');
const A = globalThis.OJ.Absicht;
const I = bauen(fs.readFileSync('docs/INHALT.md', 'utf8'));
let gruen = 0, rot = 0;
const ok = (n, b, mehr) => { if (b) { gruen++; console.log('  ✓ ' + n); } else { rot++; console.log('  ✗ ROT: ' + n + (mehr !== undefined ? '  → ' + JSON.stringify(mehr) : '')); } };
const raum = (t, nr) => { const e = A.verstehen(t, I); ok(`„${t}“ → ${I.stationen[nr].titel}`, e.stationen[0] === nr, e.stationen); return e; };
raum('Ich möchte heute das Bad reinigen', 3);
raum('Küche putzen', 2);
raum('Ich will den Kleiderschrank ausmisten', 5);
raum('Garten', 9);
raum('Schimmel im Keller', 8);
raum('die Wäsche riecht muffig', 4);
raum('Fenster putzen', 6);
raum('Flur aufräumen', 1);
raum('Parkett wischen', 7);
const rm = raum('Ich möchte Reinigungsmittel reinigen', 0);
ok('„Reinigungsmittel“ → alle fünf Mittel', rm.mittel.join() === '0,1,2,3,4');
ok('„Reinigungsmittel“ findet NICHT „Eins rein, eins raus“', !rm.gewohnheiten.includes('g18'), rm.gewohnheiten);
ok('„Wie benutze ich Natron?“ → Natron', A.verstehen('Wie benutze ich Natron?', I).mittel.join() === '1');
const f = A.verstehen('Rotweinfleck auf der Bluse', I);
ok('„Rotweinfleck auf der Bluse“ → Fleckenkarte Rotwein', f.flecken.map(i => I.flecken[i].name).includes('Rotwein'), f.flecken);
ok('„Backofen sauber machen“ → Schritt 2.8', A.verstehen('Backofen sauber machen', I).schritte.includes('s2.8'));
ok('„Was steht im Oktober an?“ → Monat 10', A.verstehen('Was steht im Oktober an?', I).monat === 10);
ok('„Bad“ bringt passende Gewohnheiten (Dusche abziehen)', A.gewohnheitenFuer(3, I).includes('g4'));
ok('„Bad“ nennt Essig und Zitronensäure als Mittel', [0, 4].every(i => A.mittelFuer(3, I).includes(i)));
ok('Unsinn wird nicht verstanden', !A.verstehen('blabla quatsch', I).verstanden);
ok('Leer wird nicht verstanden', !A.verstehen('', I).verstanden);
ok('Umlaute egal: „Kuche“/„Küche“/„KUECHE“', ['Küche', 'KUECHE'].every(t => A.verstehen(t, I).stationen[0] === 2));
console.log(`\n${gruen} grün · ${rot} ROT`);
process.exitCode = rot ? 1 : 0;
